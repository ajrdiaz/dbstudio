const LangContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('dbstudio-lang') || 'es'; } catch { return 'es'; }
  });
  useEffect(() => {
    try { localStorage.setItem('dbstudio-lang', lang); } catch { /* ignore */ }
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback((key, vars) => {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(vars[k]);
    return s;
  }, [lang]);

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

// Fallback when no provider is found: happens for a moment after Vite
// hot-reloads this file (a new context object), which used to blank the page.
function fallbackI18n() {
  let lang = 'es';
  try { lang = localStorage.getItem('dbstudio-lang') || 'es'; } catch { /* ignore */ }
  const t = (key, vars) => {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(vars[k]);
    return s;
  };
  return { lang, setLang: () => window.location.reload(), t };
}

export function useI18n() {
  return useContext(LangContext) || fallbackI18n();
}
